"""Dynamic Runtime Trace & Test Failure Correlation Engine for APEX 2.0.

Reconciles static code analysis findings with dynamic test coverage reports
(coverage.json, .coverage, coverage.xml) and test failure reports (junit.xml),
confirming dead code candidates and linking test failures directly to static findings.
"""
from __future__ import annotations

import json
import sqlite3
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from app.services.analyzers.base import FindingItem


@dataclass
class StackFrame:
    file_path: str
    line_number: int
    function_name: str


@dataclass
class CorrelatedTestFailure:
    test_name: str
    message: str
    failure_type: str
    stack_frames: list[StackFrame] = field(default_factory=list)


def parse_coverage_json(report_path: Path, root_dir: Path) -> dict[str, set[int]]:
    """Parse coverage.json file into {normalized_rel_path: set_of_executed_lines}."""
    executed_lines: dict[str, set[int]] = {}
    try:
        data = json.loads(report_path.read_text(encoding="utf-8", errors="ignore"))
        files = data.get("files", {})
        for abs_file, details in files.items():
            rel_file = _normalize_path(abs_file, root_dir)
            lines = set(details.get("executed_lines", []))
            executed_lines[rel_file] = lines
    except Exception:
        pass
    return executed_lines


def parse_sqlite_coverage(db_path: Path, root_dir: Path) -> dict[str, set[int]]:
    """Parse standard .coverage SQLite file generated by coverage.py."""
    executed_lines: dict[str, set[int]] = {}
    try:
        conn = sqlite3.connect(str(db_path))
        cur = conn.cursor()
        # Query file path and executed line numbers
        rows = cur.execute("SELECT f.path, l.lineno FROM file f JOIN line l ON f.id = l.file_id").fetchall()
        for file_path, lineno in rows:
            rel = _normalize_path(file_path, root_dir)
            if rel not in executed_lines:
                executed_lines[rel] = set()
            executed_lines[rel].add(lineno)
        conn.close()
    except Exception:
        pass
    return executed_lines


def parse_coverage_xml(xml_path: Path, root_dir: Path) -> dict[str, set[int]]:
    """Parse Cobertura-style coverage.xml file."""
    executed_lines: dict[str, set[int]] = {}
    try:
        tree = ET.parse(str(xml_path))
        root = tree.getroot()
        for cls_node in root.findall(".//class"):
            filename = cls_node.get("filename")
            if not filename:
                continue
            rel = _normalize_path(filename, root_dir)
            if rel not in executed_lines:
                executed_lines[rel] = set()
            for line_node in cls_node.findall(".//line"):
                hits = int(line_node.get("hits", "0"))
                if hits > 0:
                    executed_lines[rel].add(int(line_node.get("number", "0")))
    except Exception:
        pass
    return executed_lines


def parse_junit_xml(xml_path: Path, root_dir: Path) -> list[CorrelatedTestFailure]:
    """Parse JUnit XML test failure report, extracting stack frames for correlation."""
    failures: list[CorrelatedTestFailure] = []
    try:
        tree = ET.parse(str(xml_path))
        root = tree.getroot()
        for testcase in root.findall(".//testcase"):
            tc_name = testcase.get("name", "unknown_test")
            classname = testcase.get("classname", "")
            full_test_name = f"{classname}.{tc_name}" if classname else tc_name

            for failure in testcase.findall("failure"):
                msg = failure.get("message", "")
                text = failure.text or ""
                frames = _extract_frames_from_traceback(text, root_dir)
                failures.append(
                    CorrelatedTestFailure(
                        test_name=full_test_name,
                        message=msg or text.splitlines()[-1] if text else "Test failed",
                        failure_type=failure.get("type", "AssertionError"),
                        stack_frames=frames,
                    )
                )
    except Exception:
        pass
    return failures


def _normalize_path(file_path_str: str, root_dir: Path) -> str:
    """Normalize file path to forward-slashes relative to root_dir."""
    p = Path(file_path_str)
    try:
        if p.is_absolute():
            rel = p.relative_to(root_dir)
        else:
            rel = p
    except ValueError:
        rel = p
    return str(rel).replace("\\", "/").lstrip("./")


def _extract_frames_from_traceback(traceback_text: str, root_dir: Path) -> list[StackFrame]:
    """Extract File ..., line X, in func frames from python traceback text."""
    frames: list[StackFrame] = []
    import re
    # Pattern: File "path/to/file.py", line 42, in func_name
    pattern = re.compile(r'File\s+"([^"]+)",\s+line\s+(\d+),\s+in\s+([^\n\r]+)')
    for match in pattern.finditer(traceback_text):
        f_path = match.group(1)
        l_num = int(match.group(2))
        fn_name = match.group(3).strip()
        norm_file = _normalize_path(f_path, root_dir)
        frames.append(StackFrame(file_path=norm_file, line_number=l_num, function_name=fn_name))
    return frames


class DynamicTraceReconciler:
    """Reconciles static analysis findings with dynamic execution traces and test failures."""

    def __init__(self, root_dir: Path) -> None:
        self.root_dir = root_dir
        self.executed_lines: dict[str, set[int]] = {}
        self.test_failures: list[CorrelatedTestFailure] = []
        self._discover_and_load_reports()

    def _discover_and_load_reports(self) -> None:
        """Scan root for standard coverage and test artifacts."""
        # 1. coverage.json
        for cov_json in self.root_dir.glob("**/coverage.json"):
            if not self._is_ignored(cov_json):
                self.executed_lines.update(parse_coverage_json(cov_json, self.root_dir))

        # 2. .coverage sqlite
        cov_sqlite = self.root_dir / ".coverage"
        if cov_sqlite.is_file():
            self.executed_lines.update(parse_sqlite_coverage(cov_sqlite, self.root_dir))

        # 3. coverage.xml
        for cov_xml in self.root_dir.glob("**/coverage.xml"):
            if not self._is_ignored(cov_xml):
                self.executed_lines.update(parse_coverage_xml(cov_xml, self.root_dir))

        # 4. junit.xml / test-results.xml
        for junit in list(self.root_dir.glob("**/junit*.xml")) + list(self.root_dir.glob("**/test-results*.xml")):
            if not self._is_ignored(junit):
                self.test_failures.extend(parse_junit_xml(junit, self.root_dir))

    def _is_ignored(self, p: Path) -> bool:
        return any(part in {".git", "venv", ".venv", "node_modules", "__pycache__"} for part in p.parts)

    def reconcile_findings(self, findings: list[FindingItem]) -> list[FindingItem]:
        """Upgrade verified dead code and correlate test failure traces to static findings."""
        has_coverage = len(self.executed_lines) > 0
        has_failures = len(self.test_failures) > 0

        updated_findings: list[FindingItem] = []

        for item in findings:
            finding = item
            f_path = finding.file or ""
            l_num = finding.line or 0

            # 1. Reconcile dead code with coverage traces
            if has_coverage and f_path in self.executed_lines:
                executed_set = self.executed_lines[f_path]
                if finding.rule_id in {"AST-UNREFERENCED-PRIVATE-SYMBOL", "AST-UNREACHABLE-CODE"}:
                    if l_num in executed_set:
                        # Statically unreferenced, but dynamically executed -> suppress or remark as dynamic dispatch
                        finding.confidence = 0.30
                        finding.evidence += f"\n[Dynamic Trace]: Executed dynamically in test suite (line {l_num}). Likely dynamic dispatch or reflection."
                    else:
                        # Both statically unreferenced AND unexecuted in dynamic tests -> confirmed dead code
                        finding.rule_id = "CONFIRMED-DEAD-CODE"
                        finding.confidence = 1.0
                        finding.severity = "medium"
                        finding.evidence += f"\n[Dynamic Trace]: Confirmed dead code — 0 executions detected across test suite for line {l_num}."

            # 2. Correlate test failure stack traces with finding
            if has_failures and f_path and l_num > 0:
                for failure in self.test_failures:
                    matching_frame = next(
                        (frame for frame in failure.stack_frames if frame.file_path == f_path and abs(frame.line_number - l_num) <= 3),
                        None,
                    )
                    if matching_frame:
                        finding.confidence = min(1.0, finding.confidence + 0.15)
                        corr_info = f"\n[Correlated Test Failure]: Test '{failure.test_name}' failed at {matching_frame.file_path}:{matching_frame.line_number} ({failure.message[:150]})."
                        if corr_info not in finding.evidence:
                            finding.evidence += corr_info
                            finding.title += " (Corroborated by Test Failure)"

            updated_findings.append(finding)

        return updated_findings
